import os
import re
import json
import time
import shutil
import logging
import http.cookiejar
from datetime import datetime
from typing import Optional, Dict, Any

logger = logging.getLogger("yt_manager")

MODULES_DIR = os.path.dirname(os.path.abspath(__file__))
BOT_ROOT = os.path.abspath(os.path.join(MODULES_DIR, ".."))
COOKIE_FILE_NAME = "youtube_cookies.txt"
ALT_COOKIE_FILE_NAME = "cookies.txt"

COOKIE_PATH = os.path.join(BOT_ROOT, COOKIE_FILE_NAME)
ALT_COOKIE_PATH = os.path.join(BOT_ROOT, ALT_COOKIE_FILE_NAME)

DEFAULT_USER_AGENT = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
    "AppleWebKit/537.36 (KHTML, like Gecko) "
    "Chrome/128.0.0.0 Safari/537.36"
)

GOOGLE_AUTH_NAMES = {
    "sid", "hsid", "ssid", "apisid", "sapisid", "login_info",
    "pref", "ysc", "visitor_info1_live", "nid", "socs", "consent",
    "account_chooser", "osid", "sidcc", "wide", "session"
}


def format_as_netscape_cookies(content: str) -> str:
    """
    Takes arbitrary cookie content:
    - Already valid Netscape format
    - JSON cookies array (from Cookie-Editor, EditThisCookie)
    - Raw HTTP 'Cookie:' header or 'key=value; key2=value2' string
    And converts/normalizes it into valid Netscape format.
    """
    if not content or not content.strip():
        return ""

    raw = content.strip()

    # 1. Check if already Netscape format
    lines = raw.splitlines()
    has_netscape_header = any("netscape" in line.lower() or "cookie file" in line.lower() for line in lines[:5])
    has_tab_delimited_data = any(len(line.split("\t")) >= 6 for line in lines if line and not line.startswith("#"))
    
    if has_netscape_header and has_tab_delimited_data:
        # Already valid Netscape, ensure correct top header and mirror cookies
        cleaned_lines = []
        if not lines[0].startswith("# Netscape HTTP Cookie File"):
            cleaned_lines.append("# Netscape HTTP Cookie File")
            cleaned_lines.append("# http://curl.haxx.se/rfc/cookie_spec.html")
            cleaned_lines.append("# This file was generated by yt_manager! Edit at your own risk.")
            cleaned_lines.append("")
        
        seen_yt = set()
        seen_google = set()
        pending_mirror_to_yt = []
        pending_mirror_to_google = []

        for line in lines:
            line_str = line.rstrip()
            if not line_str:
                continue
            cleaned_lines.append(line_str)
            if not line_str.startswith("#"):
                parts = line_str.split("\t")
                if len(parts) >= 7:
                    domain = parts[0].lower()
                    name = parts[5]
                    if "youtube" in domain:
                        seen_yt.add(name)
                        pending_mirror_to_google.append(parts)
                    elif "google" in domain:
                        seen_google.add(name)
                        pending_mirror_to_yt.append(parts)

        # Mirror google auth cookies to .youtube.com
        for parts in pending_mirror_to_yt:
            name = parts[5]
            if name not in seen_yt:
                cleaned_lines.append(f".youtube.com\tTRUE\t{parts[2]}\t{parts[3]}\t{parts[4]}\t{parts[5]}\t{parts[6]}")
                seen_yt.add(name)

        # Mirror youtube auth cookies to .google.com
        for parts in pending_mirror_to_google:
            name = parts[5]
            if name not in seen_google:
                cleaned_lines.append(f".google.com\tTRUE\t{parts[2]}\t{parts[3]}\t{parts[4]}\t{parts[5]}\t{parts[6]}")
                seen_google.add(name)

        return "\n".join(cleaned_lines) + "\n"

    # 2. Check if JSON format
    if (raw.startswith("[") and raw.endswith("]")) or (raw.startswith("{") and raw.endswith("}")):
        try:
            parsed = json.loads(raw)
            if isinstance(parsed, dict):
                parsed = [parsed]
            if isinstance(parsed, list) and len(parsed) > 0 and isinstance(parsed[0], dict):
                out = [
                    "# Netscape HTTP Cookie File",
                    "# http://curl.haxx.se/rfc/cookie_spec.html",
                    "# This file was generated by yt_manager! Edit at your own risk.",
                    ""
                ]
                default_expiry = int(time.time() + 315360000)
                for item in parsed:
                    name = str(item.get("name", "")).strip().replace("\t", "").replace("\n", "")
                    val = str(item.get("value", "")).strip().replace("\t", " ").replace("\n", "")
                    if not name:
                        continue
                    domain = str(item.get("domain", ".youtube.com")).strip()
                    if not domain.startswith("."):
                        domain = "." + domain
                    path = str(item.get("path", "/")).strip() or "/"
                    secure = "TRUE" if item.get("secure", True) else "FALSE"
                    include_sub = "TRUE" if domain.startswith(".") else "FALSE"
                    expiry = str(int(item.get("expirationDate") or item.get("expiry") or default_expiry))
                    out.append(f"{domain}\t{include_sub}\t{path}\t{secure}\t{expiry}\t{name}\t{val}")
                return "\n".join(out) + "\n"
        except Exception:
            pass

    # 3. Raw HTTP Cookie format (e.g. key1=val1; key2=val2; ...)
    if raw.lower().startswith("cookie:"):
        raw = raw[7:].strip()

    # Split on semicolons or newlines
    raw_tokens = re.split(r"[;\r\n]+", raw)
    cookies_dict = {}

    for token in raw_tokens:
        token = token.strip()
        if not token or token.startswith("#"):
            continue
        if "=" not in token:
            continue
        name, _, val = token.partition("=")
        name = name.strip().replace("\t", "").replace("\n", "").replace("\r", "")
        val = val.strip().replace("\t", " ").replace("\n", "").replace("\r", "")
        if name and val:
            cookies_dict[name] = val

    if not cookies_dict:
        return ""

    out = [
        "# Netscape HTTP Cookie File",
        "# http://curl.haxx.se/rfc/cookie_spec.html",
        "# This file was generated by yt_manager! Edit at your own risk.",
        ""
    ]
    # Far-future expiration timestamp (year 2038 epoch)
    expiry = "2147483647"

    for name, val in cookies_dict.items():
        is_secure = "TRUE" if (name.startswith("__Secure-") or name.startswith("__Host-")) else "FALSE"
        
        # Add for .youtube.com
        out.append(f".youtube.com\tTRUE\t/\t{is_secure}\t{expiry}\t{name}\t{val}")

        # If it's a Google auth cookie or session cookie, also add for .google.com
        name_lower = name.lower()
        if (
            name_lower in GOOGLE_AUTH_NAMES
            or name.startswith("__Secure-")
            or name.startswith("__Host-")
            or "sid" in name_lower
            or "auth" in name_lower
            or "login" in name_lower
        ):
            out.append(f".google.com\tTRUE\t/\t{is_secure}\t{expiry}\t{name}\t{val}")

    return "\n".join(out) + "\n"


def get_cookies_path() -> Optional[str]:
    """Returns the absolute path to cookies.txt if it exists and is not empty."""
    for p in [COOKIE_PATH, ALT_COOKIE_PATH]:
        if os.path.isfile(p) and os.path.getsize(p) > 20:
            return os.path.abspath(p)
    return None


def has_cookies() -> bool:
    """Returns True if a valid YouTube cookies file is installed."""
    return get_cookies_path() is not None


def get_cookies_status() -> Dict[str, Any]:
    """Returns metadata about the active cookies file."""
    path = get_cookies_path()
    if not path:
        return {"exists": False, "size": 0, "path": "", "updated_at": "", "lines": 0}

    size = os.path.getsize(path)
    mtime = datetime.fromtimestamp(os.path.getmtime(path)).strftime("%Y-%m-%d %H:%M:%S")
    lines = 0
    try:
        cj = http.cookiejar.MozillaCookieJar(path)
        cj.load(ignore_discard=True, ignore_expires=True)
        lines = len(cj)
    except Exception:
        try:
            with open(path, "r", encoding="utf-8", errors="ignore") as f:
                lines = sum(1 for line in f if line.strip() and not line.startswith("#"))
        except Exception:
            pass

    return {
        "exists": True,
        "size": size,
        "path": path,
        "updated_at": mtime,
        "lines": lines
    }


def save_cookies_text(content: str) -> bool:
    """Formats and saves Netscape cookie content to youtube_cookies.txt and cookies.txt."""
    content = content.strip()
    if not content:
        return False

    formatted = format_as_netscape_cookies(content)
    if not formatted or len(formatted.strip()) < 10:
        logger.error("Failed to parse cookie content into Netscape format")
        return False

    try:
        with open(COOKIE_PATH, "w", encoding="utf-8") as f:
            f.write(formatted)
        with open(ALT_COOKIE_PATH, "w", encoding="utf-8") as f:
            f.write(formatted)

        # Validate with MozillaCookieJar
        try:
            cj = http.cookiejar.MozillaCookieJar(COOKIE_PATH)
            cj.load(ignore_discard=True, ignore_expires=True)
            logger.info(f"✓ Validated {len(cj)} cookies loaded via MozillaCookieJar")
        except Exception as val_e:
            logger.warning(f"MozillaCookieJar validation warning: {val_e}")

        logger.info(f"✓ YouTube cookies saved to {COOKIE_PATH} ({len(formatted)} chars)")
        return True
    except Exception as e:
        logger.error(f"Failed to write cookies file: {e}")
        return False


def save_cookies_from_file(source_file: str) -> bool:
    """Reads uploaded cookies file, converts to Netscape format, and saves."""
    if not os.path.isfile(source_file):
        return False
    try:
        content = ""
        for enc in ["utf-8", "latin-1", "cp1252"]:
            try:
                with open(source_file, "r", encoding=enc) as f:
                    content = f.read()
                if content:
                    break
            except Exception:
                continue

        if not content:
            return False

        return save_cookies_text(content)
    except Exception as e:
        logger.error(f"Failed to process cookies file {source_file}: {e}")
        return False


def delete_cookies() -> bool:
    """Deletes existing cookies files."""
    deleted = False
    for p in [COOKIE_PATH, ALT_COOKIE_PATH]:
        if os.path.isfile(p):
            try:
                os.remove(p)
                deleted = True
            except Exception:
                pass
    return deleted


def is_youtube_url(url: str) -> bool:
    """Checks whether the given URL is a YouTube link."""
    if not url:
        return False
    u = url.lower().strip()
    return any(k in u for k in [
        "youtube.com",
        "youtu.be",
        "youtube-nocookie.com",
        "music.youtube.com"
    ])


def build_yt_dlp_flags(url: str) -> str:
    """
    Returns extra yt-dlp arguments specifically optimized for YouTube:
    - --cookies if available
    - optimized web/android player clients to bypass bot blocks
    - custom user agent
    """
    flags = []
    
    # 1. Attach cookies if present
    c_path = get_cookies_path()
    if c_path:
        flags.append(f'--cookies "{c_path}"')

    # 2. Add YouTube specific extractor args and user agent
    if is_youtube_url(url):
        flags.append(f'--user-agent "{DEFAULT_USER_AGENT}"')
        flags.append('--extractor-args "youtube:player_client=web,mweb,web_safari;player_skip=webpage,configs"')
        flags.append('--no-check-certificates')
        flags.append('--geo-bypass')

    return " " + " ".join(flags) if flags else ""


def build_yt_format_string(quality: str) -> str:
    """Constructs robust yt-dlp format string for YouTube videos."""
    q = (quality or "").strip().lower()
    if q in ("best", "un", "1080", "1080p"):
        return "bestvideo[height<=1080]+bestaudio/best[height<=1080]/best"
    elif q in ("720", "720p"):
        return "bestvideo[height<=720]+bestaudio/best[height<=720]/best"
    elif q in ("480", "480p"):
        return "bestvideo[height<=480]+bestaudio/best[height<=480]/best"
    elif q in ("360", "360p"):
        return "bestvideo[height<=360]+bestaudio/best[height<=360]/best"
    elif q in ("240", "240p"):
        return "bestvideo[height<=240]+bestaudio/best[height<=240]/best"
    elif q.isdigit():
        return f"bestvideo[height<={q}]+bestaudio/best[height<={q}]/best"
    return "bestvideo+bestaudio/best"

